/// whisper.cpp's Metal code checks the macOS version with `@available`, which calls
/// `__isPlatformVersionAtLeast` from clang's runtime. rustc links without that runtime, so it is
/// added here; without it a build for an older macOS than the one building fails to link.
fn link_clang_runtime() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
        return;
    }
    let Ok(output) = std::process::Command::new("clang").arg("--print-runtime-dir").output() else {
        return;
    };
    let dir = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if output.status.success() && std::path::Path::new(&dir).join("libclang_rt.osx.a").is_file() {
        println!("cargo:rustc-link-search=native={dir}");
        println!("cargo:rustc-link-lib=static=clang_rt.osx");
    }
}
